package ai.yuki.chuxue.data

/**
 * 「Ta 正在做的事」清单 —— 界面直接渲染的纯判定。
 *
 * ## 为什么要有它
 * 聊天页只有"正在输入…"和思考气泡，用户看不出**后台还在忙什么**。
 * 回复发完、气泡落定之后，记忆提取和上下文压缩可能还在跑，可那段时间界面上
 * 什么都没有 —— 用户会以为它卡了，或者以为已经完事可以退出。
 * 把"正在做的事"列出来，等待就从"静悄悄"变成"看得见"。
 *
 * ## 顺序写死在这里
 * 按流水线的真实先后：**回你 → 记下 → 整理**。不让界面各排各的 ——
 * 两处各排一次，同一条信息迟早会长出两种样子。
 *
 * ## 文案中性（用户 2026-10-05）
 * 条目里**不出现人称代词**，抬头由界面统一写「Ta 正在做的事」。
 * 用户的人设千奇百怪，条目里写死"她/他"都是替用户认定性别。
 *
 * ⚠️ 只驱动界面：**不进 `messages`、不进请求体**（缓存红线）。
 */
object Activity {

    enum class Kind(val label: String) {
        /** 正在生成这一轮的回复（与"正在输入…"同源，但这里是**清单视角**）。 */
        REPLY("正在回你"),

        /** 记忆提取跑着 —— 她自己记下这次聊到的事。 */
        MEMORY("正在记下你说的事"),

        /** 上下文压缩跑着（长对话才会触发）。 */
        COMPRESS("正在整理前面的对话"),
    }

    /** 现在**正在做的事**，空表 = 界面不显示这张卡。 */
    fun current(reply: Boolean, memory: Boolean, compressing: Boolean): List<Kind> = buildList {
        if (reply) add(Kind.REPLY)
        if (memory) add(Kind.MEMORY)
        if (compressing) add(Kind.COMPRESS)
    }
}
