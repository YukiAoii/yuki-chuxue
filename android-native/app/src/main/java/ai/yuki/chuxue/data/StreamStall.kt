package ai.yuki.chuxue.data

/**
 * 「她是不是卡住了」—— 流式生成期间，**最后一次收到内容**到现在隔了多久。
 *
 * ## 为什么需要它
 * 用户真机上的几类问题（抖动、删除无效、发了不回）有一个共同的观感：
 * **"我不知道她到底在不在动"** —— 屏幕上要么是一颗转圈，要么是停在一半的字，
 * 唯一能判断的办法是盯着看，然后猜。这一层要把那句"好像卡住了"**由界面自己说出来**。
 *
 * ## 它只喂给界面，一个字都不进请求体
 * ⚠️ 判定结果只驱动**一行警告**（[ChatViewModel.stalled] → 气泡下方那行字）。
 * 它**不写进 `messages`、不进 `plan.body`** —— 那会是冻结前缀的一部分，
 * 一旦写进去，从那一轮起该会话的缓存全部失效（见 `架构红线文档`）。
 * 所以这里刻意做成**纯函数**：只有"时间进、布尔出"，没有状态、没有 IO，
 * 也就没有任何一条路径能把它漏进消息体。可以逐条钉断言（见 `StreamStallTest`）。
 *
 * ## 为什么判据是"距上次内容的间隔"，而不是"总共等了多久"
 * 长回复本来就要打很久：总时长 40 秒不代表卡了，**中途 10 秒没有任何新内容**才是信号。
 * 所以每收到一块内容（正文 [ChatStreamEvent.Delta] 或思考 [ChatStreamEvent.Reasoning]）
 * 都要重置计时 —— 思考也算"她在动"。
 */
object StreamStall {

    /**
     * 多久没有新内容就认为"卡住了"（毫秒）。
     *
     * 10 秒是权衡：正常网络下相邻两块通常几十到几百毫秒就到；
     * 给到 30 秒（= 首字看门狗那一档）用户已经盯了很久却什么提示都没有。
     * 这一档**只是提醒**（一行字），不是错误 —— 内容一到就消失，也不打断这一轮。
     */
    const val TIMEOUT_MS = 10_000L

    /**
     * 从最后一次收到内容（[lastTokenAt]）到此刻（[now]）是否已经"卡住"。
     *
     * @param lastTokenAt 最后一次收到内容的时刻（`System.currentTimeMillis()`）。
     *   **`<= 0` 表示这一轮还没开始（或已经结束）** —— 此时无论 [now] 多大都返回 false，
     *   避免看门狗在空闲状态下误报（结束时把计时清零，正是为了这一条）。
     * @param now 当前时刻。
     */
    fun hasStalled(lastTokenAt: Long, now: Long): Boolean =
        lastTokenAt > 0L && now - lastTokenAt >= TIMEOUT_MS

    /**
     * 「首字看门狗」这一轮该等多久（`0` = **不要起**）。
     *
     * ## 为什么非流式必须是 0（v0.61.21 修）
     * 看门狗管的是"请求发出去了、**一个事件都没来过**"。而**非流式**（"整段出现"）
     * 根本不存在"首字"这回事 —— 整段回复是一次性回来的，中途**必然**没有任何事件。
     * 于是 30 秒一到它就把一轮**完全正常**的请求当成超时掐掉：
     * 用户看到的是"她没回你"，真相却是客户端自己把这条流杀了。
     * HTTP 那边本来就有 120 秒读超时兜底，这里不必再插一道更短的闸。
     *
     * @param baseMs 流式模式下的等待上限
     * @param nonStream 这一轮是不是非流式
     */
    fun firstByteWatchdogMs(baseMs: Long, nonStream: Boolean): Long =
        if (nonStream) 0L else baseMs
}
