package ai.yuki.chuxue.data

/**
 * 表情包的预置情绪分类（用户 2026-09-28 要求，依据 `表情包参考文档.txt`：
 * 「预置 5 个默认分类，支持自定义」）。
 *
 * ⚠️ **"支持自定义"那一半已经撤掉了**（v0.43.1，用户要求）。
 * 理由是它在**提示词那一侧根本对不上**：模型只认下面这几个标签名，
 * 用户新加的"得意"它永远不会输出 —— 图存得进去，却一辈子抽不到。
 * 所以 [DEFAULTS] 现在是**唯一**的分类来源。
 * 管理页仍会显示历史遗留的自定义分类（好让那些图可见、可删），但不再能新建。
 *
 * ## ⚠️ 这几个词是**两侧共用的契约**
 * 它们同时是：
 * 1. 管理界面上的分类选项；
 * 2. **发给模型的那套标签名** —— 附录里会告诉模型"情绪强烈时可以输出 `[开心]` 这样的标签"。
 *
 * 所以**改这里的字必须同时改提示词**，否则模型输出的标签会永远匹配不上，
 * 表现为「表情包功能开着，但一张图都不发」——而且不报错。
 * `EmojiCategoriesTest` 有一条断言把两侧钉在一起。
 */
object EmojiCategories {

    /** 预置分类（顺序即界面上的排列顺序）。 */
    val DEFAULTS = listOf("开心", "难过", "生气", "害羞", "爱意")

    /**
     * 标签在模型输出里的形状：`[开心]`。
     *
     * 用方括号而不是别的记号，是因为它**不容易与正常文字撞车**，
     * 而且模型对"方括号包住的词是个标记"这件事有很强的先验。
     */
    private val TAG_REGEX = Regex("""\[([^\[\]\n]{1,8})]""")

    /**
     * 连续空格（标签被摘掉后留下的空档）—— 模式是 `[ \t]{2,}`。
     *
     * ⚠️ 提为常量（v0.50.5）：它原来是**在 [stripTags] 里现场构造的**，
     * 而 [stripTags] 在聊天列表里**每条助手消息、每次重组**都要跑一遍 ——
     * 滚动时等于每帧新建若干正则对象。正则编译不便宜，这是可避免的浪费。
     */
    private val MULTI_SPACE_REGEX = Regex("[ \\t]{2,}")

    /** 从一段模型输出里**抽出**情绪标签（可能不止一个）。返回的是标签里的词，不含括号。 */
    fun extractTags(text: String): List<String> =
        TAG_REGEX.findAll(text).map { it.groupValues[1].trim() }.toList()

    /**
     * 把标签**从正文里摘掉** —— 用户不该在气泡里看到 `[开心]` 这种记号。
     *
     * ⚠️ 只摘掉**认得出来的**那些（属于 [DEFAULTS] 或用户在用的分类）：
     * 模型偶尔会输出 `[1]` `[注]` 这类非情绪方括号，把它们也删掉会**吃掉正文**。
     */
    fun stripTags(text: String, known: Collection<String>): String =
        TAG_REGEX
            .replace(text) { m ->
                if (m.groupValues[1].trim() in known) "" else m.value
            }
            // ⚠️ 标签删掉后会在原位留下一道空隙（`我 [开心] 好开心` → `我  好开心`），
            // 气泡里看起来就是一个莫名其妙的空档。把连续空格收敛成一个。
            // 只收敛空格与制表符，**不碰换行** —— 换行是用户有意的排版。
            .replace(MULTI_SPACE_REGEX, " ")
            .trim()

    /**
     * 教模型使用标签的那段提示词 —— **它只能进附录**。
     *
     * ## ⚠️ 为什么这条注释要写得这么重
     * 这段文字是**每轮都相同**的（内容固定），看上去"很适合"放进人设或全局前缀 ——
     * 那是错的：那两层是**冻结前缀**，一旦往里面加东西，**该层之下所有会话的缓存全部作废**
     *（本项目最贵的教训，见 `memory/architecture.md`）。
     *
     * 而放进**附录**（每轮追加的前缀末端）则完全安全：附录本来就不参与缓存命中。
     * 所以它在 `ChatViewModel` 里是**拼到 memories 后面**进去的，不是拼到人设里。
     *
     * ## 为什么要显式列出分类名
     * 不列的话，模型会自由发明标签（`[高兴]` `[开心]` `[喜悦]` 各来一遍），
     * 而本地图库只按**知道的分类**取图 —— 结果就是"功能开着，但一张都发不出来"。
     */
    fun promptHint(): String = buildString {
        append("【表情包】当情绪明显时，可以在回复结尾单独用方括号标一个情绪标签，")
        append("例如：")
        append("好呀，我陪你。[开心]")
        append("。可用的标签只有这几个：")
        append(DEFAULTS.joinToString("、") { "[$it]" })
        append("。一次最多一个。没有合适的心情就不要标，不要为了发图而标。")
    }
}
